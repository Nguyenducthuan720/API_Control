        [HttpPost]
        public async Task<IActionResult> Add([FromBody] PromotionPrograms.Request.AddOrEdit request)
        {
            try
            {
                var giftsJson = JsonConvert.SerializeObject(request.Gifts);
                var detailsJson = JsonConvert.SerializeObject(request.Details);
                request.Gifts = null;
                request.Details = null;

                Dictionary<string, object> parameters = new()
                {
                    { "@type", "ADD" },
                    { "@language", _UserInfo.Language },
                    { "@UserIDCurent", _UserInfo.UserID },
                    { "@CmpnID", _UserInfo.CmpnID },
                    { "@GiftsJson", giftsJson },
                    { "@DetailsJson", detailsJson }
