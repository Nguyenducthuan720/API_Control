    [HttpPost]
    public async Task<IActionResult> GetByID([FromBody] Trainings.Request.GetByOID request)
    {
        try
        {
            Dictionary<string, object> parameters = new()
            {
                { "@type", "GET-BYID" },
                { "@language", _UserInfo.Language },
                { "@UserIDCurent", _UserInfo.UserID },
                { "@CmpnID", _UserInfo.CmpnID }
            };
            DataResponse dataResponse = await Function.GetDataResponse(parameters, _SecondaryDB, _ConfigurationDB, _ProcedureName, request);

            if (dataResponse.Result!.Count > 1 && dataResponse.Result[0].Count > 0)
            {
                dynamic result = dataResponse.Result[0][0];
                result.Contents = dataResponse.Result[1];
                result.Questions = dataResponse.Result[2];
                result.Results = dataResponse.Result[3];
                result.Attendances = dataResponse.Result[4];
                result.WebResults = dataResponse.Result[5];
                result.Progress = dataResponse.Result[6];
                result.Histories = dataResponse.Result[7];
                dataResponse.Result = result;
            }
            else
            {
                dataResponse.Result = null;
            }
            return Ok(dataResponse);
        }
        catch (Exception ex)
        {
            return Ok(new DataResponse(ex.Message, "", "-1"));
        }
    }

