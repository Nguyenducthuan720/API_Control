namespace APISmartCity.Controllers.Ver2;
[ApiExplorerSettings(GroupName = "Functions.VehicleMaintenances")]
[Route("api/[controller]/[action]")]
[Authorize]
[ApiController]
public class VehicleMaintenancesController : Controller
{
    private readonly UserInfo _UserInfo;
    private readonly string _ConfigurationDB;
    private readonly string _SecondaryDB;
    private readonly string _ProcedureName = "ExecVehicleMaintenances";

    public VehicleMaintenancesController(UserInfo userInfo)
    {
        _UserInfo = userInfo;
        _ConfigurationDB = Global.ListDB?.Find(item => item.DBType == "CON")?.DBString!;
        _SecondaryDB = Global.ListDB?.Find(item => item.DBType == "SHP")?.DBString!;
    }

    [HttpPost]
    public async Task<IActionResult> GetMonitor()
    {
        try
        {
            Dictionary<string, object> parameters = new()
            {
                { "@type", "GET-MONITOR" },
                { "@language", _UserInfo.Language },
                { "@UserIDCurent", _UserInfo.UserID },
                { "@CmpnID", _UserInfo.CmpnID }
            };
            DataResponse dataResponse = await Function.GetDataResponse(parameters, _SecondaryDB, _ConfigurationDB, _ProcedureName, null);
            if (dataResponse.Result!.Count > 1 && dataResponse.Result[0].Count > 0)
            {
                dataResponse.Result = new
                {
                    Summary = dataResponse.Result[0],
                    Details = dataResponse.Result[1]
                };
            }
            else
            {
                dataResponse.Result = null;
            }
            return Ok(dataResponse);
        }
        catch (Exception ex)
        {
            return Ok(new DataResponse(ex.Message, "", "-1"));
        }
    }
